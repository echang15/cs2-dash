"""Build public/weapon-skin-images.js: weapon class + paintkit -> Steam-hosted skin image link.

Usage: python3 tools/gen_skin_images.py <skins.json> <base_weapons.json> public/weapon-skin-images.js
Inputs: https://raw.githubusercontent.com/ByMykel/CSGO-API/main/public/api/en/skins.json
        https://raw.githubusercontent.com/ByMykel/CSGO-API/main/public/api/en/base_weapons.json (stock renders)
Images are not stored here; the dashboard loads them from Steam's image servers at runtime.
"""
import json, sys

src, base_src, out = sys.argv[1:4]
PREFIX = 'https://community.akamai.steamstatic.com/economy/image/'
MIRROR = 'https://raw.githubusercontent.com/ByMykel/counter-strike-image-tracker/'
skins = json.load(open(src))
by_class = {}
skipped = 0
for s in skins:
    wid = (s.get('weapon') or {}).get('id') or ''
    if not wid.startswith('weapon_'):
        # Vanilla knives are listed under HUD ids (sfui_wpnhud_knifekaram); the real class is in original.name
        wid = (s.get('original') or {}).get('name') or wid
    img = s.get('image') or ''
    if not wid.startswith('weapon_') or not img.startswith(PREFIX):
        skipped += 1
        continue
    pattern = s.get('pattern') or {}
    key = pattern.get('id') or ''          # '' = vanilla (knives only)
    label = pattern.get('name') or 'Vanilla'
    by_class.setdefault(wid, {})[key] = [img[len(PREFIX):], label]

# Stock (unskinned) renders become each weapon's '' entry; vanilla knife entries from the skin list win if present
stock = 0
for b in json.load(open(base_src)):
    wid = str(b.get('id') or '').replace('base_weapon-', '')
    img = b.get('image') or ''
    if not wid.startswith('weapon_'):
        continue
    if img.startswith(PREFIX):
        ref = img[len(PREFIX):]
    elif img.startswith(MIRROR):
        ref = img  # a few stock renders are only on the CSGO-API image mirror: keep the full link
    else:
        continue
    table = by_class.setdefault(wid, {})
    if '' not in table:
        table[''] = [ref, 'Stock']
        stock += 1
print('stock renders added', stock)

body = json.dumps(by_class, separators=(',', ':'), sort_keys=True)
open(out, 'w').write(
    '/* Generated by tools/gen_skin_images.py from the CSGO-API skin list. Do not edit by hand. */\n'
    'window.WEAPON_SKIN_IMAGE_PREFIX = %s;\n'
    'window.WEAPON_SKIN_IMAGES = %s;\n' % (json.dumps(PREFIX), body))
print('weapons', len(by_class), 'skins', sum(len(v) for v in by_class.values()), 'skipped', skipped, 'bytes', len(body))
